#!/usr/bin/env python3
"""Build and run the IR storage benchmark (bench/ir_storage).

Variants (see ir_api.h):
  A-today      pointers into the arena, mlir_api_impl.c's layout   (ir_a_today.c)
  A-lean       pointers into the arena, one allocation per op       (ir_a_lean.c)
  B-pool       32-bit indices into vectors that double by realloc;
               operands in one shared pool                          (ir_b_pool.c)
  B-pool+hint  B-pool, vectors reserved up front from a size hint
  B-pool-seg   B-pool, vectors made of fixed-size arena segments
               (no reallocation, no copying)                        (-DB_SEGMENTED)
  B-arena      32-bit indices; per-op arena arrays of operand
               indices, per-value use arrays                        (ir_b_arena.c)

Each is built with each available compiler:
  gcc    -O2, hosted (libc memcpy), corec arena/buddy/platform   ($CC or gcc)
  clang  -O2, same                                                ($CLANG, clang, or the
                                                                   linux pixi env's clang)
  tinyc  one-TU build through `tinyc --emit=elf` with corec-stdlib ($TINYC or ./tinyc_native)

For gcc and clang every translation unit is compiled separately (no LTO), so
the workload calls the IR API out of line, as passes call mlir_api_impl.c
today. The tinyc build is one TU (tinyc does not inline).

Runs are pinned to one CPU with taskset and the variants are interleaved: each
round runs every variant once, in a rotated order. Each process builds the
module REPS + 1 times from a fresh context; the first iteration is a warmup
(its build time is reported as "cold build"). Reported times are medians over
all warm iterations of all rounds. Peak RSS comes from one extra
single-iteration process per variant (wait4 ru_maxrss). The run aborts if any
run of any variant or compiler disagrees on the op count, the rewrite counts
or the checksums. "IR bytes/op" counts bytes in use (arena bytes handed out
plus vector elements in use); vector slack shows up only in peak RSS.

Usage:
  python bench/ir_storage/run.py [--scales 10000,100000,1000000]
      [--compilers gcc,clang,tinyc] [--rounds 5] [--cpu N] [--json out.json]
"""
import argparse
import json
import os
import shutil
import statistics
import subprocess
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent

# (label, source, handle bits, extra -D defines, size hint passed to the run)
VARIANTS = [
    ("A-today", "a_today", 64, [], 0),
    ("A-lean", "a_lean", 64, [], 0),
    ("B-pool", "b_pool", 32, [], 0),
    ("B-pool+hint", "b_pool", 32, [], 1),
    ("B-pool-seg", "b_pool", 32, ["B_SEGMENTED"], 0),
    ("B-arena", "b_arena", 32, [], 0),
]
PHASES = ["build", "walk", "uses", "rewrite"]

COREC = ["io", "buddy", "arena", "scratch", "format", "math", "string",
         "strbuf", "mem", "numconv", "assert", "exit"]
UNITY_COREC = ["assert", "exit", "mem", "string", "numconv", "format",
               "strbuf", "io", "buddy", "arena", "scratch"]
UNITY_STDLIB = ["string_impl", "stdlib", "stdio", "printf"]


def find_clang():
    cand = os.environ.get("CLANG") or shutil.which("clang")
    if cand:
        return cand
    # The upstream pixi environment has gcc only; the linux one has clang.
    for root in (ROOT, Path(os.environ.get("PIXI_PROJECT_ROOT", ROOT))):
        p = root / ".pixi" / "envs" / "linux" / "bin" / "clang"
        if p.exists():
            return str(p)
    return None


def build_cc(cc, impl, bits, defines, out):
    srcs = [HERE / "workload.c", HERE / f"ir_{impl}.c"]
    srcs += [ROOT / "corec" / "base" / f"{n}.c" for n in COREC]
    srcs += [ROOT / "corec" / "platform" / "platform_linux.c"]
    cmd = [cc, "-O2", "-w", "-DBENCH_HOSTED", "-DPLATFORM_SKIP_ENTRY",
           f"-DIR_HANDLE_BITS={bits}"] + [f"-D{d}" for d in defines] + [
           "-I", str(ROOT / "corec"), "-I", str(HERE),
           "-o", str(out)] + [str(s) for s in srcs] + ["-lm"]
    subprocess.run(cmd, check=True)


def build_tinyc(tinyc, impl, bits, defines, out, build_dir):
    unity = build_dir / f"unity_{out.name}.c"

    def inc(p):
        return os.path.relpath(p, build_dir).replace(os.sep, "/")

    lines = ["/* Generated by bench/ir_storage/run.py. */",
             "#define SINGLE_TU_BUILD 1",
             "#define COREC_STDLIB_PROVIDES_MEM 1",
             "#define PLATFORM_SKIP_ENTRY 1",
             f"#define IR_HANDLE_BITS {bits}"] + [f"#define {d} 1" for d in defines] + [
             "#include <stddef.h>", "#include <stdint.h>", "#include <stdarg.h>",
             "#include <stdio.h>", "#include <stdlib.h>", "#include <string.h>",
             f'#include "{inc(HERE / "workload.c")}"',
             f'#include "{inc(HERE / f"ir_{impl}.c")}"']
    lines += [f'#include "{inc(ROOT / "corec" / "base" / (n + ".c"))}"' for n in UNITY_COREC]
    lines += [f'#include "{inc(ROOT / "corec-stdlib" / "stdlib" / (n + ".c"))}"' for n in UNITY_STDLIB]
    lines += [f'#include "{inc(ROOT / "corec" / "platform" / "platform_linux.c")}"']
    unity.write_text("\n".join(lines) + "\n")
    cmd = [tinyc, "--emit=elf", "--lowering=native", "--host-varargs",
           "-I", str(ROOT / "corec-stdlib" / "stdlib"), "-I", str(ROOT / "corec"),
           "-I", str(HERE), "-o", str(out), str(unity)]
    subprocess.run(cmd, check=True, cwd=ROOT)


def run_one(binary, n, reps, hint, cpu):
    cmd = ["taskset", "-c", str(cpu), str(binary), str(n), str(reps), str(hint)]
    p = subprocess.Popen(cmd, stdout=subprocess.PIPE)
    out = p.stdout.read().decode()
    _, status, ru = os.wait4(p.pid, 0)
    if status != 0:
        sys.exit(f"{binary} failed with status {status}")
    rows = []
    for line in out.splitlines():
        kv = dict(f.split("=", 1) for f in line.split())
        rows.append(kv)
    return rows, ru.ru_maxrss * 1024


def reps_for(n):
    if n <= 10000:
        return 40
    if n <= 100000:
        return 10
    return 3


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--scales", default="10000,100000,1000000")
    ap.add_argument("--compilers", default="gcc,clang,tinyc")
    ap.add_argument("--rounds", type=int, default=5)
    ap.add_argument("--cpu", type=int, default=(os.cpu_count() or 1) - 1)
    ap.add_argument("--build-dir", default=str(HERE / "_build"))
    ap.add_argument("--json")
    args = ap.parse_args()

    build_dir = Path(args.build_dir)
    build_dir.mkdir(parents=True, exist_ok=True)
    scales = [int(s) for s in args.scales.split(",")]

    compilers = {}
    for name in args.compilers.split(","):
        if name == "gcc":
            cc = os.environ.get("CC") or shutil.which("gcc")
        elif name == "clang":
            cc = find_clang()
        elif name == "tinyc":
            cc = os.environ.get("TINYC") or str(ROOT / "tinyc_native")
            if not Path(cc).exists():
                cc = None
        else:
            sys.exit(f"unknown compiler {name}")
        if not cc:
            print(f"# skipping {name}: compiler not found", file=sys.stderr)
            continue
        compilers[name] = cc

    bins = {}
    for comp, cc in compilers.items():
        for label, impl, bits, defines, _ in VARIANTS:
            out = build_dir / f"{comp}_{impl}{''.join('_' + d.lower() for d in defines)}"
            if out not in bins.values():
                if comp == "tinyc":
                    build_tinyc(cc, impl, bits, defines, out, build_dir)
                else:
                    build_cc(cc, impl, bits, defines, out)
            bins[(comp, label)] = out

    signature = {}   # n -> (ops, folded, erased, checksums), identical everywhere
    load_start = os.getloadavg()
    t_start = time.time()
    results = {}
    for comp in compilers:
        for n in scales:
            reps = reps_for(n)
            labels = [v[0] for v in VARIANTS]
            hints = {v[0]: v[4] for v in VARIANTS}
            samples = {lb: {ph: [] for ph in PHASES} for lb in labels}
            cold = {lb: [] for lb in labels}
            meta = {}
            for r in range(args.rounds):
                order = labels[r % len(labels):] + labels[:r % len(labels)]
                for lb in order:
                    rows, _ = run_one(bins[(comp, lb)], n, reps, hints[lb], args.cpu)
                    for row in rows:
                        sig = (row["ops"], row["folded"], row["erased"], row["h"])
                        if signature.setdefault(n, sig) != sig:
                            sys.exit(f"{lb} ({comp}, n={n}) disagrees: {sig} vs {signature[n]}")
                    cold[lb].append(int(rows[0]["build_ns"]))
                    for row in rows[1:]:
                        for ph in PHASES:
                            samples[lb][ph].append(int(row[ph + "_ns"]))
                    meta[lb] = rows[0]
            for lb in labels:
                _, rss = run_one(bins[(comp, lb)], n, 0, hints[lb], args.cpu)
                med = {ph: statistics.median(samples[lb][ph]) for ph in PHASES}
                impl = lb
                results[(comp, n, impl)] = {
                    "ops": int(meta[impl]["ops"]),
                    "bytes": int(meta[impl]["bytes"]),
                    "rss": rss,
                    "median_ns": med,
                    "cold_build_ns": statistics.median(cold[lb]),
                    "folded": int(meta[impl]["folded"]),
                    "erased": int(meta[impl]["erased"]),
                }
            print(f"# done {comp} n={n}", file=sys.stderr)
    load_end = os.getloadavg()

    print(f"CPU {args.cpu} (taskset), {args.rounds} rounds, designs interleaved; "
          f"load average {load_start[0]:.2f} at start, {load_end[0]:.2f} at end; "
          f"{time.time() - t_start:.0f} s")
    print()
    for comp in compilers:
        for n in scales:
            base = results[(comp, n, "A-today")]
            r0 = results[(comp, n, "A-lean")]
            print(f"### {comp}, {base['ops']} ops "
                  f"({base['folded']} folded, {base['erased']} erased by the rewrite)")
            print()
            print("| design | build ms | walk ms | uses ms | rewrite ms | total ms | "
                  "vs A-today | vs A-lean | cold build ms | IR bytes/op | peak RSS MB |")
            print("|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|")
            tot_base = sum(base["median_ns"].values())
            tot_lean = sum(r0["median_ns"].values())
            for impl in (v[0] for v in VARIANTS):
                r = results[(comp, n, impl)]
                m = r["median_ns"]
                tot = sum(m.values())
                cells = [f"{m[ph] / 1e6:.3f}" for ph in PHASES]
                print(f"| {impl} | " + " | ".join(cells) +
                      f" | {tot / 1e6:.3f} | {tot / tot_base:.2f} | {tot / tot_lean:.2f}"
                      f" | {r['cold_build_ns'] / 1e6:.3f} | {r['bytes'] / r['ops']:.0f}"
                      f" | {r['rss'] / 2**20:.1f} |")
            print()

    if args.json:
        out = [{"compiler": c, "n": n, "impl": i, **v} for (c, n, i), v in results.items()]
        Path(args.json).write_text(json.dumps({"load_start": load_start, "load_end": load_end,
                                               "cpu": args.cpu, "results": out}, indent=1))


if __name__ == "__main__":
    main()
